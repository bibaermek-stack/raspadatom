def vac_to_air(wl_vac_nm):
    """Вакуумдағы толқын ұзындығы -> стандартты ауадағы (Peck & Reeder 1972, NIST ASD қолданатын формула)."""
    s2 = (1e3 / wl_vac_nm) ** 2  # σ² (мкм⁻²)
    n = 1.0 + 1e-8 * (8060.51 + 2480990.0 / (132.274 - s2) + 17455.7 / (39.32957 - s2))
    return wl_vac_nm / n
